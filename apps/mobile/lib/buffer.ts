/**
 * Полоса буфера для мобильного плеера.
 *
 * В браузере `video.buffered` — список диапазонов, и там полоса честно
 * состоит из нескольких отрезков. expo-video отдаёт буфер **одним числом**:
 * `bufferedPosition` — «докуда плеер успел забуферить», в секундах. Диапазонов
 * у нативного плеера через JS не видно, поэтому и отрезок один.
 *
 * Начинается он от текущей позиции, а не от нуля, и это не упрощение.
 * Про то, что позади проигрывателя что-то лежит в буфере, мы не знаем ничего:
 * нативный плеер этого не сообщает. Нарисовать серое от нуля — значит
 * утверждать про буфер то, чего нам не говорили. Отрезок «отсюда и до
 * докуда дотянулись» — ровно то, что `bufferedPosition` и означает.
 */

/** Отрезок в долях длительности: 0 — начало, 1 — конец. */
export interface BufferedBand {
  start: number;
  end: number;
}

/**
 * Отрезок «впереди уже скачано», или `null`, если показывать нечего.
 *
 * `null` вместо пустого отрезка намеренно: у вызывающего кода тогда нет
 * способа случайно отрисовать прямоугольник нулевой или отрицательной ширины.
 */
export function bufferedBand(
  position: number,
  bufferedPosition: number,
  duration: number,
): BufferedBand | null {
  // Позиция — база для обеих долей. NaN из моста прошёл бы через Math.min
  // насквозь (Math.max(0, NaN) === NaN), и ширина уехала бы в стиль как есть.
  if (!Number.isFinite(position) || position < 0) return null;
  // -1 — документированное «состояние буфера неизвестно» (плеер ничего не
  // играет); прочий мусор из моста идёт туда же.
  if (!Number.isFinite(bufferedPosition)) return null;
  // Нулевая длительность — это не только «долю считать не от чего»: при
  // нулевой позиции 0/0 даёт NaN, а `NaN <= NaN` ложно, и вырожденный отрезок
  // ушёл бы наружу вместо null.
  if (!Number.isFinite(duration) || duration <= 0) return null;

  const start = Math.min(1, position / duration);
  const end = Math.min(1, bufferedPosition / duration);
  // Буфер, не дошедший до текущей позиции, вырождается здесь сам: end не
  // больше start. Отдельной проверки `bufferedPosition <= position` нет
  // намеренно — она недостижима, обе ветки всё равно приходят сюда, и
  // мутационный прогон это подтвердил: замена `<=` на `<` не роняет ни одного
  // теста. Отрицательный `bufferedPosition` ловится тут же.
  if (end <= start) return null;
  return { start, end };
}

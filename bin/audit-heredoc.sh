#!/usr/bin/env bash
# Проверка тела серверного heredoc в deploy.sh перед отправкой.
#
# Зачем отдельный скрипт. Серверная половина уходит через `ssh bash -s <<REMOTE`
# с НЕквотированным маркером, поэтому локальная оболочка раскрывает тело до
# отправки. Ошибка здесь не видна локально и не проявляется как ошибка: на
# сервер уезжает другая строка, и проверка либо молча зеленеет, либо падает
# невнятным сообщением чужой утилиты.
#
# Уже дважды. Экранирование потерялось у $(...), из-за чего STALE уезжал
# пустым и проверка кэша ссылок стала вечно зелёной, ничего не проверяя.
# Затем доллар-решётка в регулярке sed раскрылась как число позиционных
# аргументов и превратила шаблон в мусор — деплой упал на «unterminated s
# command», хотя строка в файле выглядит верной.
#
#   ./bin/audit-heredoc.sh              # проверить bin/deploy.sh
#   ./bin/audit-heredoc.sh <файл>       # проверить другой файл (для самопроверки:
#                                       # подсунуть заведомо испорченную копию)
#
# Выход 1 — есть находки, деплоить нельзя.
set -uo pipefail

# Локаль отбирается у awk намеренно. На маке LANG=C.UTF-8 — имя, которого в
# системе нет: BSD awk переключается в многобайтовый режим и на первой же
# строке с кириллицей падает с «towc: multibyte conversion failure», НЕ
# напечатав находок. Скрипт тогда рапортует «чисто» на любом файле — проверка,
# которая не умеет упасть. Все шаблоны здесь ASCII, поэтому побайтовый режим
# ничего не теряет и не зависит от того, кто скрипт вызвал.
export LC_ALL=C

cd "$(dirname "$0")/.." || exit 2

# Файл можно подменить аргументом — иначе проверку нечем проверить: чтобы
# убедиться, что она ловит находки, нужен заведомо испорченный файл.
FILE=${1:-bin/deploy.sh}

# Переменные, которые ЗАКОННО подставляет локальная оболочка: они известны
# здесь и должны уехать значениями. Всё остальное обязано быть с обратным слешем.
#
# Список приходится дополнять вручную при каждой новой локальной переменной —
# это и есть смысл: незаэкранированная подстановка ловится здесь, а не выясняется
# на сервере по «вечно зелёной» проверке. RELEASES_DIR/CURRENT/PREVIOUS/TS — из
# раскладки релизов (bin/deploy.sh).
LOCAL_OK='APP_DIR|SERVER|PUBLIC_URL|HTTPS_URL|API_INTERNAL|TMDB_KEY|RELEASES_DIR|CURRENT|PREVIOUS|TS'

FINDINGS=$(awk -v local_ok="$LOCAL_OK" '
  /bash -s <<REMOTE/ { inblock=1; next }
  /^REMOTE$/         { inblock=0; next }
  !inblock           { next }
  {
    line=$0
    bad=0; why=""

    # Экранированные доллары и кавычки локальная оболочка не трогает — убираем
    # их сразу, чтобы не ловить ложные срабатывания на \$(...) и \$1.
    rest=line
    gsub(/\\\$/, "", rest)
    gsub(/\\`/, "", rest)

    # Обратные кавычки выполняются локально — и внутри комментариев тоже.
    if (rest ~ /`/) { bad=1; why=why " обратные кавычки;" }

    # $(...) — подстановка команды на маке.
    if (rest ~ /\$\(/) { bad=1; why=why " подстановка $(...) без экранирования;" }

    # Всё, что осталось от $ — либо разрешённое локальное имя, либо ошибка.
    #
    # Идём по строке символом, а не через match()+substr(): RSTART затирается
    # вложенным match() на имени, и «сдвиг за доллар» превращался в «сдвиг на
    # символ» — один и тот же $FOO печатался столько раз, сколько символов
    # перед ним, и настоящая находка тонула в тридцати копиях себя.
    n=length(rest); i=1
    while (i<=n) {
      if (substr(rest,i,1) != "$" || i==n) { i++; continue }
      d=substr(rest,i+1,1)

      if (d == "{") {
        # ${FOO} — раньше этот вид не проверялся вообще.
        tail=substr(rest, i+2)
        if (match(tail, /^[A-Za-z_][A-Za-z0-9_]*/)) {
          ident=substr(tail, 1, RLENGTH)
          if (ident !~ "^(" local_ok ")$") { bad=1; why=why " незаэкранированный ${" ident "};" }
          i=i+2+RLENGTH; continue
        }
      } else if (d ~ /[A-Za-z_]/) {
        tail=substr(rest, i+1)
        if (match(tail, /^[A-Za-z_][A-Za-z0-9_]*/)) {
          ident=substr(tail, 1, RLENGTH)
          if (ident !~ "^(" local_ok ")$") { bad=1; why=why " незаэкранированный $" ident ";" }
          i=i+1+RLENGTH; continue
        }
      } else if (d ~ /[#?!@*0-9]/) {
        bad=1; why=why " специальный параметр $" d ";"
        i=i+2; continue
      }
      i++
    }

    if (bad) printf "%s:%d:%s\n    %s\n", FILENAME, FNR, why, line
  }
' "$FILE")

if [ -n "$FINDINGS" ]; then
  echo "$FINDINGS"
  echo
  echo "Найдено в теле heredoc — деплоить нельзя: экранируйте обратным слешем." >&2
  exit 1
fi

echo "heredoc в $FILE: чисто"
